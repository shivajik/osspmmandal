export function getSectionsForBranch(slug) {
  const keys = BRANCH_SECTION_KEYS[slug];
  if (!keys) return SECTION_LIST;
  return keys
    .map((k) => ALL_SECTIONS.find((s) => s.key === k))
    .filter(Boolean);
}

